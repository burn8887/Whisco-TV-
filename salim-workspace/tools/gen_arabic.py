#!/usr/bin/env python3
"""Generate the Arabic string tables for both native apps from i18n/ar.json.

The JSON is the single source of truth: English source text -> Arabic, plus regex
patterns for strings that carry numbers (distances, timers, counts). Run after editing:

    python3 salim-workspace/tools/gen_arabic.py
"""
from __future__ import annotations
import json
from pathlib import Path

CAPSULE = Path(__file__).resolve().parent.parent
SOURCE = CAPSULE / "i18n" / "ar.json"
KOTLIN = CAPSULE / "apps/salim-android/app/src/main/java/app/salim/ArabicStrings.kt"
SWIFT = CAPSULE / "apps/salim-ios/Salim/ArabicStrings.swift"
HEADER = "Generated by tools/gen_arabic.py from i18n/ar.json. Do not edit by hand."


def kt(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '"'


def sw(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    exact, patterns = data["exact"], data["patterns"]
    lines = [f"// {HEADER}", "package app.salim", "", "internal val AR_EXACT: Map<String, String> = mapOf("]
    lines += [f"    {kt(k)} to {kt(v)}," for k, v in exact.items()]
    lines += [")", "", "internal val AR_PATTERNS: List<Pair<String, String>> = listOf("]
    lines += [f"    {kt(p)} to {kt(t)}," for p, t in patterns]
    lines += [")", ""]
    KOTLIN.write_text("\n".join(lines), encoding="utf-8")
    lines = [f"// {HEADER}", "", "let arExact: [String: String] = ["]
    lines += [f"    {sw(k)}: {sw(v)}," for k, v in exact.items()]
    lines += ["]", "", "let arPatterns: [(String, String)] = ["]
    lines += [f"    ({sw(p)}, {sw(t)})," for p, t in patterns]
    lines += ["]", ""]
    SWIFT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(exact)} strings and {len(patterns)} patterns written for Android and iOS")


if __name__ == "__main__":
    main()
